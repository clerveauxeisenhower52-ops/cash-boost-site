-- Disposable PostgreSQL fixture only. Never run against Supabase production.
CREATE EXTENSION IF NOT EXISTS pgcrypto;
CREATE SCHEMA IF NOT EXISTS auth;
CREATE TABLE auth.users (
  id uuid PRIMARY KEY
);

CREATE TABLE public.orders (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  user_id uuid REFERENCES auth.users(id) ON DELETE CASCADE,
  total_htg numeric NOT NULL DEFAULT 100,
  payment_method text,
  status text,
  auto_validation_reason text
);

CREATE TABLE public.wallets (
  user_id uuid PRIMARY KEY REFERENCES auth.users(id) ON DELETE CASCADE,
  balance_htg numeric(14,2) NOT NULL DEFAULT 0 CHECK (balance_htg >= 0),
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  public_no bigint GENERATED BY DEFAULT AS IDENTITY UNIQUE NOT NULL
);

CREATE TABLE public.wallet_transactions (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  user_id uuid NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
  type text NOT NULL CHECK (type IN ('deposit','purchase','transfer_in','transfer_out','refund','adjustment')),
  amount_htg numeric(14,2) NOT NULL,
  balance_after numeric(14,2) NOT NULL,
  provider text,
  reference text,
  order_id text,
  created_at timestamptz NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX wallet_tx_one_purchase ON public.wallet_transactions(order_id)
  WHERE type = 'purchase' AND order_id IS NOT NULL;
CREATE UNIQUE INDEX wallet_tx_one_refund ON public.wallet_transactions(order_id)
  WHERE type = 'refund' AND order_id IS NOT NULL;
CREATE UNIQUE INDEX wallet_tx_one_refund_per_order ON public.wallet_transactions(reference)
  WHERE type = 'refund' AND reference IS NOT NULL;
CREATE INDEX wallet_tx_user_idx ON public.wallet_transactions(user_id, created_at DESC);
